/// Proving key of the value circuit (BN254 Groth16).
pub type SnarkProvingKey = ProvingKey<Bn254>;

/// Field element type of the value circuit.
pub type Field = Fr;

/// Number of new notes in one value-hiding spend (fixed by the circuit).
pub const NEW_NOTES: usize = 2;

/// Value range bits enforced for every value and for `cap - v_old`.
pub const VALUE_BITS: usize = 64;

/// Number of public inputs of the circuit (`fee, cap, cmu, poseidon,
/// c_old, c_new0, c_new1`).
pub const PUBLIC_INPUTS: usize = 5 + NEW_NOTES;

// ---------------------------------------------------------------------
// Poseidon
// ---------------------------------------------------------------------

/// Poseidon state width (rate 2 + capacity 1).
pub const POSEIDON_WIDTH: usize = 3;
/// Full rounds (`R_F`).
pub const POSEIDON_FULL_ROUNDS: usize = 8;
/// Partial rounds (`R_P`).
pub const POSEIDON_PARTIAL_ROUNDS: usize = 57;
/// S-box exponent.
pub const POSEIDON_ALPHA: u64 = 5;

/// Domain tag: note preimage digest.
const DOM_NOTE: u64 = 1;
/// Domain tag: commitment of the spent note (bound to its `cmu`).
const DOM_COMMIT_OLD: u64 = 2;
/// Domain tag: commitment of a new note.
const DOM_COMMIT_NEW: u64 = 3;

/// The Poseidon parameters. Deterministic and public (nothing secret):
/// `ark`/`mds` come from the Grain LFSR keyed by
/// `(field bits = 254, width = 3, R_F = 8, R_P = 57)`.
pub fn poseidon_config() -> &'static PoseidonConfig<Fr> {
    static CONFIG: OnceLock<PoseidonConfig<Fr>> = OnceLock::new();
    CONFIG.get_or_init(|| {
        let rate = POSEIDON_WIDTH - 1;
        let (ark, mds) = find_poseidon_ark_and_mds::<Fr>(
            Fr::MODULUS_BIT_SIZE as u64,
            rate,
            POSEIDON_FULL_ROUNDS as u64,
            POSEIDON_PARTIAL_ROUNDS as u64,
            0,
        );
        PoseidonConfig {
            full_rounds: POSEIDON_FULL_ROUNDS,
            partial_rounds: POSEIDON_PARTIAL_ROUNDS,
            alpha: POSEIDON_ALPHA,
            ark,
            mds,
            rate,
            capacity: 1,
        }
    })
}

/// Off-circuit Poseidon hash of a fixed-length list of field elements.
pub fn poseidon_hash(inputs: &[Fr]) -> Fr {
    let mut sponge = PoseidonSponge::<Fr>::new(poseidon_config());
    for x in inputs {
        sponge.absorb(x);
    }
    sponge.squeeze_native_field_elements(1)[0]
}

/// In-circuit Poseidon hash (mirrors [`poseidon_hash`]).
fn poseidon_hash_var(
    cs: &ConstraintSystemRef<Fr>,
    inputs: &[FpVar<Fr>],
) -> Result<FpVar<Fr>, SynthesisError> {
    let mut sponge = PoseidonSpongeVar::<Fr>::new(cs.clone(), poseidon_config());
    for x in inputs {
        sponge.absorb(x)?;
    }
    Ok(sponge.squeeze_field_elements(1)?.remove(0))
}

/// Splits bytes into 11-byte big-endian field limbs (88 bits each,
/// always below the modulus).
fn limbs_of(bytes: &[u8]) -> Vec<Fr> {
    bytes.chunks(11).map(Fr::from_be_bytes_mod_order).collect()
}

/// Off-circuit Poseidon digest of a note preimage
/// `(spending_pub, value, rcm)`: absorbs
/// `[DOM_NOTE, pub limbs (3), value, rcm limbs (3)]`. This is NOT the
/// on-chain SHA-256 `cmu`; the two bind the same preimage jointly.
pub fn poseidon_cmu(spending_pub: &[u8; 33], value: u64, rcm: &[u8; 32]) -> Fr {
    let mut inputs = vec![Fr::from(DOM_NOTE)];
    inputs.extend(limbs_of(spending_pub));
    inputs.push(Fr::from(value));
    inputs.extend(limbs_of(rcm));
    poseidon_hash(&inputs)
}

/// Value commitment bound to the note's `cmu` (used for `C_old`):
/// `Poseidon(DOM_COMMIT_OLD, value, rcm, cmu_field)`, where
/// `cmu_field` is the on-chain `cmu` read as a field element. The
/// verifier derives it from the spent pool output, so a proof for a
/// different note cannot verify. Binding is the collision resistance
/// of Poseidon; hiding comes from the secret 254-bit `rcm`.
pub fn value_commitment(value: u64, rcm: &[u8; 32], cmu: &[u8; 32]) -> Fr {
    poseidon_hash(&[
        Fr::from(DOM_COMMIT_OLD),
        Fr::from(value),
        Fr::from_be_bytes_mod_order(rcm),
        Fr::from_be_bytes_mod_order(cmu),
    ])
}

/// Unbound value commitment (used for new-note slots `C_new`):
/// `Poseidon(DOM_COMMIT_NEW, value, rcm)`.
pub fn new_commitment(value: u64, rcm: &[u8; 32]) -> Fr {
    poseidon_hash(&[
        Fr::from(DOM_COMMIT_NEW),
        Fr::from(value),
        Fr::from_be_bytes_mod_order(rcm),
    ])
}

