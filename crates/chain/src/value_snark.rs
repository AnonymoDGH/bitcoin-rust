/// Public statement of one value-hiding spend.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ValueTranscript {
    /// Public miner fee (sats).
    pub fee: u64,
    /// Funding cap of the spent note (sats, public from the ledger).
    pub cap: u64,
    /// On-chain note commitment (from the spent pool output).
    pub cmu: Fr,
    /// Poseidon hash of the note preimage (from the pool script on v3
    /// notes; recomputed from the opening on legacy notes).
    pub poseidon: Fr,
    /// Commitment of the spent note.
    pub c_old: Fr,
    /// Commitments of the two new notes.
    pub c_new: [Fr; NEW_NOTES],
}

/// Private witness for one value-hiding spend.
#[derive(Clone, Copy)]
pub struct ValueWitness {
    pub v_old: u64,
    pub rcm_old: [u8; 32],
    pub spending_pub: [u8; 33],
    pub v_new: [u64; NEW_NOTES],
    pub rcm_new: [[u8; 32]; NEW_NOTES],
}

struct ValueCircuit {
    transcript: Option<ValueTranscript>,
    witness: Option<ValueWitness>,
}

fn ok<T>(v: Option<T>) -> Result<T, SynthesisError> {
    v.ok_or(SynthesisError::AssignmentMissing)
}

/// Enforces `var < 2^VALUE_BITS` (and `var >= 0`) by bit decomposition.
fn range_check(
    cs: &ConstraintSystemRef<Fr>,
    var: &FpVar<Fr>,
    value: Option<u64>,
) -> Result<(), SynthesisError> {
    let mut bits = Vec::with_capacity(VALUE_BITS);
    for i in 0..VALUE_BITS {
        bits.push(Boolean::new_witness(cs.clone(), || {
            ok(value.map(|v| (v >> i) & 1 == 1))
        })?);
    }
    Boolean::le_bits_to_fp_var(&bits)?.enforce_equal(var)
}

impl ConstraintSynthesizer<Fr> for ValueCircuit {
    fn generate_constraints(self, cs: ConstraintSystemRef<Fr>) -> ark_relations::r1cs::Result<()> {
        let t = self.transcript;
        let w = self.witness;
        // Public inputs, in verification order.
        let fee = FpVar::new_input(cs.clone(), || ok(t.map(|t| Fr::from(t.fee))))?;
        let cap = FpVar::new_input(cs.clone(), || ok(t.map(|t| Fr::from(t.cap))))?;
        let cmu = FpVar::new_input(cs.clone(), || ok(t.map(|t| t.cmu)))?;
        let poseidon = FpVar::new_input(cs.clone(), || ok(t.map(|t| t.poseidon)))?;
        let c_old = FpVar::new_input(cs.clone(), || ok(t.map(|t| t.c_old)))?;
        let mut c_new = Vec::with_capacity(NEW_NOTES);
        for i in 0..NEW_NOTES {
            c_new.push(FpVar::new_input(cs.clone(), || ok(t.map(|t| t.c_new[i])))?);
        }

        // Private inputs.
        let v_old = FpVar::new_witness(cs.clone(), || ok(w.map(|w| Fr::from(w.v_old))))?;
        let pub_limbs_val = w.map(|w| limbs_of(&w.spending_pub));
        let rcm_limbs_val = w.map(|w| limbs_of(&w.rcm_old));
        let mut pub_limbs = Vec::with_capacity(3);
        let mut rcm_limbs = Vec::with_capacity(3);
        for i in 0..3 {
            pub_limbs.push(FpVar::new_witness(cs.clone(), || {
                ok(pub_limbs_val.as_ref().map(|l| l[i]))
            })?);
            rcm_limbs.push(FpVar::new_witness(cs.clone(), || {
                ok(rcm_limbs_val.as_ref().map(|l| l[i]))
            })?);
        }
        // rcm_old is *defined* by its limbs (32 big-endian bytes as
        // 11 + 11 + 10 byte limbs, reduced mod p exactly like
        // `Fr::from_be_bytes_mod_order`), so the commitment opening and
        // the preimage digest share one `rcm`.
        let base = Fr::from(256u64);
        let rcm_old = &rcm_limbs[0] * FpVar::constant(base.pow([21u64]))
            + &rcm_limbs[1] * FpVar::constant(base.pow([10u64]))
            + &rcm_limbs[2];
        let mut v_new = Vec::with_capacity(NEW_NOTES);
        let mut rcm_new = Vec::with_capacity(NEW_NOTES);
        for i in 0..NEW_NOTES {
            v_new.push(FpVar::new_witness(cs.clone(), || {
                ok(w.map(|w| Fr::from(w.v_new[i])))
            })?);
            rcm_new.push(FpVar::new_witness(cs.clone(), || {
                ok(w.map(|w| Fr::from_be_bytes_mod_order(&w.rcm_new[i])))
            })?);
        }

        // Preimage binding: Poseidon(DOM_NOTE, pub, v_old, rcm_old) == poseidon.
        let mut note_inputs = vec![FpVar::constant(Fr::from(DOM_NOTE))];
        note_inputs.extend(pub_limbs.iter().cloned());
        note_inputs.push(v_old.clone());
        note_inputs.extend(rcm_limbs.iter().cloned());
        poseidon_hash_var(&cs, &note_inputs)?.enforce_equal(&poseidon)?;

        // C_old opens, bound to the on-chain cmu.
        poseidon_hash_var(
            &cs,
            &[
                FpVar::constant(Fr::from(DOM_COMMIT_OLD)),
                v_old.clone(),
                rcm_old,
                cmu,
            ],
        )?
        .enforce_equal(&c_old)?;

        // Every new commitment opens; values are in range.
        let mut allocated = FpVar::<Fr>::zero();
        for i in 0..NEW_NOTES {
            poseidon_hash_var(
                &cs,
                &[
                    FpVar::constant(Fr::from(DOM_COMMIT_NEW)),
                    v_new[i].clone(),
                    rcm_new[i].clone(),
                ],
            )?
            .enforce_equal(&c_new[i])?;
            range_check(&cs, &v_new[i], w.map(|w| w.v_new[i]))?;
            allocated += &v_new[i];
        }
        // v_old == v_new0 + v_new1 + fee. `fee` is range-checked too so
        // the sum cannot wrap around the field.
        let fee_value = t.map(|t| t.fee);
        range_check(&cs, &fee, fee_value)?;
        v_old.enforce_equal(&(allocated + &fee))?;
        // v_old in range, and v_old <= cap via cap - v_old in range.
        range_check(&cs, &v_old, w.map(|w| w.v_old))?;
        let diff_value = match (t, w) {
            (Some(t), Some(w)) => Some(t.cap.wrapping_sub(w.v_old)),
            _ => None,
        };
        range_check(&cs, &(&cap - &v_old), diff_value)?;
        Ok(())
    }
}

/// Checks the statement against a witness without proving it.
/// `false` for inflation / over-cap / bad openings.
pub fn is_statement_satisfiable(transcript: ValueTranscript, witness: ValueWitness) -> bool {
    let circuit = ValueCircuit {
        transcript: Some(transcript),
        witness: Some(witness),
    };
    let cs = ConstraintSystem::<Fr>::new_ref();
    if circuit.generate_constraints(cs.clone()).is_err() {
        return false;
    }
    cs.is_satisfied().unwrap_or(false)
}

