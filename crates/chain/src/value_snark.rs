//! Groth16 value-hiding proofs over pool notes (Privacy Plan, Phase 3+).
//!
//! The hash-note pool reveals every spent value in the witness (the
//! funding ledger bounds it, but it is not private). This module is
//! the SNARK layer that hides spent values: a prover shows, without
//! revealing anything but the public fee, that
//!
//! * the spent note's value commitment opens
//!   (`C_old = Poseidon(DOM_OLD, v_old, rcm_old, cmu)`),
//! * the note preimage `(pub, v_old, rcm_old)` hashes to the public
//!   Poseidon digest carried by the v3 pool script,
//! * `v_old` is fully allocated: `v_old = v_new0 + v_new1 + fee`,
//! * every new value is in range and `v_old <= cap` (the issuance
//!   funding cap from `notes::funding_caps_for_block`),
//! * each new commitment opens (`C_new_i = Poseidon(DOM_NEW, v_new_i, rcm_new_i)`).
//!
//! Public inputs: `(fee, cap, cmu, poseidon, C_old, C_new0, C_new1)`.
//!
//! # Trust model: there is NO built-in key
//!
//! Groth16 security rests on the setup's toxic waste
//! (`alpha, beta, gamma, delta, tau`) being destroyed. Earlier
//! revisions of this module derived the keys from a hard-coded RNG
//! seed, which made every proof forgeable by anybody. That path is
//! gone: this module never creates keys on its own. Consensus verifies
//! only against the verifying key pinned in the chain parameters
//! (`ChainParams::snark_vk`); with no key configured every SNARK proof
//! is rejected. Keys come from [`generate_parameters`] (single party,
//! `btc-node -snark-setup`) or — required before mainnet — from a
//! multi-party ceremony (see `docs/privacy-plan.md`).
//!
//! # Hash
//!
//! Notes and commitments use the Poseidon sponge of
//! `ark-crypto-primitives` over BN254 `Fr`: width 3 (rate 2,
//! capacity 1), S-box `x^5` (a permutation, `gcd(5, p-1) = 1`),
//! 8 full + 57 partial rounds — the Poseidon paper's 128-bit-security
//! instance for `t = 3`, `alpha = 5`, BN254 — with round constants and
//! the Cauchy MDS matrix generated by the reference Grain-LFSR
//! procedure ([`find_poseidon_ark_and_mds`]). Every use is
//! domain-separated by a leading tag element and has a fixed length.

